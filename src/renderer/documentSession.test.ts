import { test } from 'node:test';
import assert from 'node:assert/strict';
const storage = new Map<string, string>();
Object.assign(globalThis, { localStorage: { getItem: (key: string) => storage.get(key) ?? null, setItem: (key: string, value: string) => storage.set(key, value), removeItem: (key: string) => storage.delete(key) } });
Object.assign(globalThis, { window: { location: { search: '' }, localStorage: globalThis.localStorage } });
Object.assign(globalThis, { document: { documentElement: { lang: 'en' }, getElementById: () => ({}), createElement: () => ({}), head: { appendChild: () => {} } } });
test('save completion does not mark newer edits or same-ID replacement saved', async () => {
  const { useStore } = await import('./state/useStore');
  const { documentSession, documentSignature } = await import('./documentSession');
  const state = useStore.getState();
  const deck = { ...state.presentation, id: 'document-test', name: 'before', slides: [] };
  state.dispatchUndo({ type: 'RESET', payload: deck }); documentSession.opened('before.gpres');
  const generation = documentSession.current().generation, signature = documentSignature(deck);
  useStore.getState().dispatchUndo({ type: 'SET', payload: { ...deck, name: 'new edit' } });
  documentSession.saved('saved.gpres', signature, generation);
  assert.equal(documentSession.isDirty(), true);
  assert.equal(useStore.getState().presentation.name, 'new edit');
  useStore.getState().dispatchUndo({ type: 'RESET', payload: { ...deck, name: 'same-id replacement' } });
  documentSession.saved('stale.gpres', signature, generation);
  assert.equal(documentSession.current().path, null);
  const loadedSignature = documentSignature(useStore.getState().presentation);
  const loadedGeneration = documentSession.current().generation;
  useStore.getState().dispatchUndo({ type: 'SET', payload: { ...useStore.getState().presentation, name: 'edit during acknowledgement' } });
  documentSession.opened('loaded.gpres', loadedSignature, loadedGeneration);
  assert.equal(documentSession.isDirty(), true);
  assert.equal(useStore.getState().presentation.name, 'edit during acknowledgement');
  const navigation = { ...deck, slides: [{ id: 'one', type: 'text' as const, content: 'One' }, { id: 'two', type: 'text' as const, content: 'Two' }] };
  useStore.getState().dispatchUndo({ type: 'RESET', payload: navigation });
  const slideReferences = useStore.getState().presentation.slides;
  useStore.getState().setLiveIndex(1);
  assert.equal(useStore.getState().liveSlideId, 'two');
  assert.equal(useStore.getState().presentation.slides, slideReferences, 'navigation preserves immutable source references');
  documentSession.unsaved();
  assert.equal(documentSession.isDirty(), true, 'an imported new document requires saving');
  assert.equal(documentSession.current().path, null);
  const importedGeneration = documentSession.current().generation;
  documentSession.saved('imported.gpres', documentSignature(useStore.getState().presentation), importedGeneration);
  assert.equal(documentSession.isDirty(), false);
});
